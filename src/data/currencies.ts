export function calculateRate(base: string, quote: string): number {
  if (base === quote) return 1.0;
  const baseToUsd = 1 / (BASE_RATES_USD[base] || 1);
  const quoteRate = BASE_RATES_USD[quote] || 1;
  return baseToUsd * quoteRate;
}
